    "def run_speed_perturbation(\n",
    "    global_config: Dict[str, Any],\n",
    "    method_config: Dict[str, Any],\n",
    ") -> Dict[str, Any]:\n",
    "    \"\"\"\n",
    "    Run speed perturbation baseline.\n",
    "\n",
    "    Parameters\n",
    "    ----------\n",
