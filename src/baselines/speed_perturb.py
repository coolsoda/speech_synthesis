    "        time_column=dataset_cfg.get(\"time_column\", \"timestamp\"),\n",
    "        label_column=dataset_cfg.get(\"label_column\", \"label\"),\n",
    "        min_sessions=dataset_cfg.get(\"min_sessions\", 2),\n",
