    "    safe_method = str(method_name).replace(\"/\", \"_\").replace(\"\\\\\", \"_\")\n",
    "    safe_subject = str(subject_id).replace(\"/\", \"_\").replace(\"\\\\\", \"_\")\n",
    "    safe_time = f\"{query_timestamp:.4f}\".replace(\".\", \"p\")\n",
    "\n",
