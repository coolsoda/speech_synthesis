    "    - XTTS-v2\n",
    "    - TTDS\n",
    "    - SCP-TTS\n",
    "\n",
    "\n",
    "This file does not reimplement those external models. Instead, it:\n",
    "\n",
    "1. Builds the same interpolation queries used by L-Flow.\n",
    "2. Creates a generation manifest CSV for an external baseline.\n",
    "3. Optionally calls a user-provided external command.\n",
    "4. Validates the generated audio files.\n",
    "5. Writes standardized synthetic_metadata.csv for downstream evaluation.\n",
    "\n",
    "Expected external generation behavior\n",
    "-------------------------------------\n",
