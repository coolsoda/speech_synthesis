    "def load_checkpoint(\n",
    "    path: PathLike,\n",
    "    model: Optional[torch.nn.Module] = None,\n",
    "    optimizer: Optional[torch.optim.Optimizer] = None,\n",
    "    scheduler: Optional[Any] = None,\n",
