    "    Returns\n",
    "    -------\n",
    "    dict\n",
    "        Full checkpoint dictionary.\n",
    "    \"\"\"\n",
    "\n",
    "    path = Path(path)\n",
    "\n",
    "    if not path.exists():\n",
    "        raise FileNotFoundError(f\"Checkpoint not found: {path}\")\n",
    "\n",
    "    checkpoint = torch.load(\n",
    "        path,\n",
    "        map_location=map_location,\n",
    "    )\n",
    "\n",
    "    if model is not None:\n",
