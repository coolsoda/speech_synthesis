    "def enable_all_baselines(config: Dict[str, Any]) -> None:\n",
    "    \"\"\"\n",
    "    Set enabled=true for all baselines in the config.\n",
    "    \"\"\"\n",
    "\n",
    "    baseline_cfg = config.get(\"baselines\", {})\n",
