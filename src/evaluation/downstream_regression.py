    "class MLPRegressorTorch(nn.Module):\n",
    "    \"\"\"\n",
    "    Simple two-layer MLP regressor.\n",
    "    \"\"\"\n",
    "\n",
    "    def __init__(\n",
    "        self,\n",
    "        input_dim: int,\n",
    "        hidden_dims: Sequence[int] = (256, 128),\n",
    "        dropout: float = 0.3,\n",
    "        activation: str = \"relu\",\n",
    "    ) -> None:\n",
    "        super().__init__()\n",
    "\n",
    "        if activation == \"relu\":\n",
    "            act_layer = nn.ReLU\n",
    "        elif activation == \"gelu\":\n",
    "            act_layer = nn.GELU\n",
    "        elif activation == \"silu\":\n",
    "            act_layer = nn.SiLU\n",
    "        else:\n",
    "            raise ValueError(f\"Unknown activation: {activation}\")\n",
    "\n",
    "        layers: List[nn.Module] = []\n",
    "\n",
    "        prev_dim = input_dim\n",
    "\n",
    "        for hidden_dim in hidden_dims:\n",
    "            layers.append(nn.Linear(prev_dim, int(hidden_dim)))\n",
    "            layers.append(act_layer())\n",
    "            layers.append(nn.Dropout(dropout))\n",
    "            prev_dim = int(hidden_dim)\n",
    "\n",
    "        layers.append(nn.Linear(prev_dim, 1))\n",
    "\n",
    "        self.net = nn.Sequential(*layers)\n",
    "\n",
    "    def forward(self, x: torch.Tensor) -> torch.Tensor:\n",
    "        return self.net(x).squeeze(-1)\n",
    "\n",
    "\n",
    "def run_mlp_regression(\n",
    "    X_train: np.ndarray,\n",
    "    y_train: np.ndarray,\n",
    "    X_test: np.ndarray,\n",
    "    config: Dict[str, Any],\n",
    "    device: torch.device,\n",
    ") -> np.ndarray:\n",
    "    \"\"\"\n",
    "    Train and evaluate MLP regressor.\n",
    "    \"\"\"\n",
    "\n",
    "    mlp_cfg = config.get(\"regressors\", {}).get(\"mlp\", {})\n",
    "    train_cfg = mlp_cfg.get(\"training\", {})\n",
    "\n",
    "    input_dim = X_train.shape[1]\n",
    "    hidden_dims = mlp_cfg.get(\"hidden_dims\", [256, 128])\n",
    "    dropout = float(mlp_cfg.get(\"dropout\", 0.3))\n",
    "    activation = mlp_cfg.get(\"activation\", \"relu\")\n",
    "\n",
    "    epochs = int(train_cfg.get(\"epochs\", 100))\n",
    "    batch_size = int(train_cfg.get(\"batch_size\", 32))\n",
    "    lr = float(train_cfg.get(\"lr\", 1e-4))\n",
    "    weight_decay = float(train_cfg.get(\"weight_decay\", 1e-4))\n",
    "    early_stopping = bool(train_cfg.get(\"early_stopping\", True))\n",
    "    patience = int(train_cfg.get(\"patience\", 10))\n",
    "\n",
    "    X_tensor = torch.tensor(X_train, dtype=torch.float32)\n",
    "    y_tensor = torch.tensor(y_train, dtype=torch.float32)\n",
    "\n",
    "    dataset = torch.utils.data.TensorDataset(X_tensor, y_tensor)\n",
    "\n",
    "    loader = DataLoader(\n",
    "        dataset,\n",
    "        batch_size=batch_size,\n",
    "        shuffle=True,\n",
    "        drop_last=False,\n",
    "    )\n",
    "\n",
    "    model = MLPRegressorTorch(\n",
    "        input_dim=input_dim,\n",
    "        hidden_dims=hidden_dims,\n",
    "        dropout=dropout,\n",
    "        activation=activation,\n",
    "    ).to(device)\n",
    "\n",
    "    optimizer = torch.optim.AdamW(\n",
    "        model.parameters(),\n",
    "        lr=lr,\n",
    "        weight_decay=weight_decay,\n",
    "    )\n",
    "\n",
    "    criterion = nn.MSELoss()\n",
    "\n",
    "    best_loss = float(\"inf\")\n",
    "    best_state = None\n",
    "    no_improve = 0\n",
    "\n",
    "    for _epoch in range(epochs):\n",
    "        model.train()\n",
    "        losses = []\n",
    "\n",
    "        for xb, yb in loader:\n",
    "            xb = xb.to(device)\n",
    "            yb = yb.to(device)\n",
    "\n",
    "            pred = model(xb)\n",
    "            loss = criterion(pred, yb)\n",
    "\n",
    "            optimizer.zero_grad(set_to_none=True)\n",
    "            loss.backward()\n",
    "            optimizer.step()\n",
    "\n",
    "            losses.append(float(loss.detach().cpu()))\n",
    "\n",
    "        epoch_loss = float(np.mean(losses))\n",
    "\n",
    "        if epoch_loss < best_loss:\n",
    "            best_loss = epoch_loss\n",
    "            best_state = {\n",
    "                key: value.detach().cpu().clone()\n",
    "                for key, value in model.state_dict().items()\n",
    "            }\n",
    "            no_improve = 0\n",
    "        else:\n",
    "            no_improve += 1\n",
    "\n",
    "        if early_stopping and no_improve >= patience:\n",
    "            break\n",
    "\n",
    "    if best_state is not None:\n",
    "        model.load_state_dict(best_state)\n",
    "\n",
    "    model.eval()\n",
    "\n",
    "    with torch.no_grad():\n",
    "        X_test_tensor = torch.tensor(X_test, dtype=torch.float32).to(device)\n",
    "        pred = model(X_test_tensor).detach().cpu().numpy()\n",
    "\n",
    "    return pred\n",
